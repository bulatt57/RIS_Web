-- Лабораторная работа №9: Схема PostgreSQL для проекта TaskControl (ПАО «Таттелеком» — ЕЦУиМС)
-- Повторный запуск схемы (п. 5.3): удаляем учебные таблицы в обратном порядке зависимостей
DROP TABLE IF EXISTS assignments CASCADE;
DROP TABLE IF EXISTS users CASCADE;
DROP TABLE IF EXISTS departments CASCADE;

-- 1. Справочник подразделений ЕЦУиМС (аналог sites в шаблоне методички)
CREATE TABLE departments (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE,
    name text NOT NULL UNIQUE
);

-- 2. Таблица пользователей (создатели поручений и исполнители)
CREATE TABLE users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name text NOT NULL,
    email text NOT NULL UNIQUE,
    role text NOT NULL CHECK (role IN ('Manager', 'Engineer', 'Dispatcher'))
);

-- 3. Главный объект — Поручения (assignments)
-- В главной таблице хранится внешний ключ department_id, а не повторяющееся название подразделения (3НФ)
CREATE TABLE assignments (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number text NOT NULL UNIQUE,
    title text NOT NULL CHECK (char_length(btrim(title)) BETWEEN 5 AND 80),
    description text NOT NULL CHECK (char_length(btrim(description)) BETWEEN 10 AND 500),
    department_id integer NOT NULL REFERENCES departments (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    status text NOT NULL DEFAULT 'New'
        CONSTRAINT assignments_status_check
        CHECK (status IN ('New', 'InProgress', 'Closed', 'Cancelled')),
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by_user_id integer NOT NULL REFERENCES users (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    assignee_user_id integer NULL REFERENCES users (id) ON UPDATE CASCADE ON DELETE SET NULL
);

-- 4. Обязательные индексы (п. 3.4 методички)
-- Ускоряет выборку поручений по статусу (WHERE status = 'New') и агрегацию по статусам (GROUP BY status)
CREATE INDEX assignments_status_idx ON assignments (status);

-- Ускоряет соединение (JOIN) таблицы поручений со справочником подразделений departments и фильтрацию по department_id
CREATE INDEX assignments_department_id_idx ON assignments (department_id);
